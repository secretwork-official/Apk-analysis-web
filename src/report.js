'use strict';
const PDFDocument = require('pdfkit');
const COLORS = { Critical: '#b91c1c', High: '#c2410c', Medium: '#a16207', Low: '#1d4ed8' };

function buildPdf(res, r, meta) {
  const doc = new PDFDocument({ margin: 44, size: 'A4', bufferPages: true });
  doc.pipe(res);
  doc.fontSize(20).fillColor('#0b1020').text('APK Analyzer by Abhigyan', { continued: false });
  doc.fontSize(10).fillColor('#555').text('Security report — generated ' + new Date().toISOString());
  doc.moveDown(0.5).strokeColor('#ccc').moveTo(44, doc.y).lineTo(551, doc.y).stroke();
  doc.moveDown();
  const sc = r.score, g = r.grade;
  doc.fontSize(14).fillColor('#000').text(`File: ${meta.filename}  (${(meta.size / 1024 / 1024).toFixed(2)} MB)`);
  doc.fontSize(28).fillColor(sc >= 75 ? '#15803d' : sc >= 45 ? '#b45309' : '#b91c1c').text(`Security score: ${sc}/100  (Grade ${g})`);
  doc.moveDown(0.5);
  if (r.manifest) {
    doc.fontSize(12).fillColor('#000').text('App details', { underline: true });
    doc.fontSize(10).fillColor('#222').text(`Package: ${r.manifest.package}\nVersion: ${r.manifest.versionName} (code ${r.manifest.versionCode})\nMin SDK: ${r.manifest.minSdk || '—'}   Target SDK: ${r.manifest.targetSdk || '—'}\nDebuggable: ${r.manifest.debuggable ? 'YES (risk)' : 'No'}   Allows backup: ${r.manifest.allowBackup ? 'Yes (risk)' : 'No'}`);
    doc.moveDown(0.5);
  }
  if (r.certificate && r.certificate.present) {
    doc.fontSize(12).text('Signing certificate', { underline: true });
    doc.fontSize(10).fillColor(r.certificate.isDebugCert ? '#b91c1c' : '#222').text(`Subject: ${r.certificate.subject}${r.certificate.isDebugCert ? '  — DEBUG CERTIFICATE, do not distribute' : ''}\nValid: ${new Date(r.certificate.validFrom).toDateString()} to ${new Date(r.certificate.validTo).toDateString()}${r.certificate.expired ? '  (EXPIRED)' : ''}\nSHA-256: ${r.certificate.sha256}`);
    doc.moveDown(0.5);
  }
  doc.fillColor('#000').fontSize(12).text(`Findings: ${r.vulnerabilities.length} issue(s), ${r.secrets.length} possible secret(s), ${r.domains.length} domain(s), ${r.urls.length} URL(s)`, { underline: true });
  doc.moveDown(0.3);
  for (const v of r.vulnerabilities) {
    doc.fontSize(10.5).fillColor(COLORS[v.severity] || '#333').text(`[${v.severity}] ${v.title}`, { continued: false });
    doc.fontSize(9).fillColor('#333').text(v.detail);
    doc.fontSize(9).fillColor('#065f46').text('Fix: ' + v.fix);
    doc.moveDown(0.3);
  }
  if (r.secrets.length) {
    doc.addPage(); doc.fontSize(14).fillColor('#000').text('Possible secrets found');
    for (const s of r.secrets) { doc.fontSize(9.5).fillColor(COLORS[s.severity] || '#333').text(`[${s.severity}] ${s.label} — ${s.match}  (${s.file})`); }
  }
  if (r.domains.length || r.urls.length) {
    doc.addPage(); doc.fontSize(14).fillColor('#000').text('Domains and URLs found (sample, see JSON for full list)');
    doc.fontSize(10).fillColor('#222');
    for (const d of r.domains.slice(0, 150)) doc.text(d.value + '  (' + d.file_count + ' file' + (d.file_count > 1 ? 's' : '') + ')');
    if (r.urls.length) { doc.moveDown(0.3).fontSize(11).text('URLs:'); for (const u of r.urls.slice(0, 150)) doc.fontSize(9).text(u.value); }
  }
  doc.addPage(); doc.fontSize(9).fillColor('#555').text('This report lists what was found inside the uploaded file automatically. A flagged item is a lead to check, not proof of a real vulnerability. Generated by APK Analyzer by Abhigyan. Only analyze apps you own or are authorized to test.');
  doc.end();
}
module.exports = { buildPdf };
